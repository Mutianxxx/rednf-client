// Position of a stem inside a job's motion list, or -1 when the client
// does not list it. Lower means earlier in the release.
inline int positionOf(std::string_view job, std::string_view stem) {
    const std::string_view *list = nullptr;
    size_t count = 0;
    if (job == "swordman") { list = kSwordman; count = std::size(kSwordman); }
    if (job == "gunner") { list = kGunner; count = std::size(kGunner); }
    if (job == "fighter") { list = kFighter; count = std::size(kFighter); }
    if (job == "mage") { list = kMage; count = std::size(kMage); }
    if (job == "priest") { list = kPriest; count = std::size(kPriest); }
    if (!list) return -1;
    for (size_t i = 0; i < count; ++i)
        if (list[i] == stem) return int(i);
    return -1;
}
