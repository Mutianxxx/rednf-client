// Authoritative skill-motion pool, in the client's OWN release order.
//
// PRIMARY (swordman / gunner): the 1031 client's own
//   character/<job>/<job>.chr -> [attack motion] + [ghost motion] +
//   [etc motion], concatenated in tag order. This is the same file and
//   version as the ANIs being played, so both membership and order are
//   source data, not a cross-version inference.
//     swordman 127 motions (3 + 2 + 122); gunner 107 (2 + 2 + 103).
//   The same CHR also carries [etc attack info] (87 / 26 .atk files),
//   i.e. the client publishes its motion -> hit-data roster in the PVF.
//
// FALLBACK (fighter / mage / priest): the 60US client's CHR tags, kept
//   because this viewer currently targets swordman + gunner first.
//
// Why a pool is needed at all: no .skl in either client names an .ani.
// A skill's release motion is an index/immediate in the executable, not
// a string. What the PVF DOES publish is the ordered animation roster
// above, so a chain matched by name can be sorted into the client's own
// release order (TripleSlash1..5, Frenzy1..4, ChargeBuster*).
//
// Cross-check: 1031 vs 60US stem overlap 97/102 (swordman), 62/68 (gunner);
// the 1031 pool additionally holds 25 swordman + 41 gunner motions that
// the 60US-era roster does not (FlowMind*, BloodSword*, ChargeBuster*,
// MultiHeadShotEx*, ...). Using the 60US roster for 1031 was a cross-version
// source mismatch. Measured effect of the switch today: NONE observable --
// grade counts and every matched chain order are identical before/after,
// because the pool only orders chains and every stem currently appearing in
// a chain has the same relative position in both rosters. This matters once
// a real skill_id -> pool-index binding is recovered; then the 1031 roster
// is the only correct index table for 1031 animations.
// ---------------------------------------------------------------------------
