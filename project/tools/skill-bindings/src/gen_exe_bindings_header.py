"""Generate include/dnf/skill_exe_bindings.hpp from bindings/<class>-skill-binding.json.

Only skills with exe-verified states (state != null) are emitted. Motion paths
are job-dir-relative -> full PVF paths; consecutive duplicate motions collapse.
"""
import json
import os

# Paths are resolved relative to this file so the pipeline is checkout-portable:
#   <project>/tools/skill-bindings/src/gen_exe_bindings_header.py
BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.normpath(os.path.join(BASE, "..", "..", "include", "dnf",
                                   "skill_exe_bindings.hpp"))

CLASSES = ["swordman", "demonicswordman", "fighter", "atfighter",
           "gunner", "atgunner", "mage", "priest"]


def hpp_str(s):
    """Escape a string as a C++ literal (ASCII safe)."""
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            b = ch.encode("utf-8")
            out.extend(f"\\{x:03o}" for x in b)
    return '"' + "".join(out) + '"'


def main():
    pairs = json.load(open(os.path.join(BASE, "evidence", "all-class-skill-state-pairs.json"),
                           encoding="utf-8"))
    verified = set()
    for p in pairs:
        if p["skill"] is not None:
            verified.add((p["skill"], p["state"]))

    def stem_of(path):
        return path.rsplit("/", 1)[-1].rsplit(".", 1)[0].lower()

    jobs = []
    total_skills = 0
    for cls in CLASSES:
        path = os.path.join(BASE, "bindings", f"{cls}-skill-binding.json")
        data = json.load(open(path, encoding="utf-8"))
        rows = []
        for sid, rec in data["skills"].items():
            skl_stem = stem_of(rec["skl"])[:8] if rec.get("skl") else None
            states = [st for st in rec["states"] if st.get("state") is not None]
            if not states:
                continue
            motions, seen = [], set()
            used_states = []
            for st in states:
                sid_i = int(sid)
                st_no = st["state"]
                ani_list = [m["ani"] for m in st["entry_motions"]]
                # keep a state only when independently justified:
                #  - queued by skill eligibility code, or
                #  - handler references this skill id alone, or
                #  - a motion stem matches the skl stem
                sole_ref = False
                # sole-ref info is not in the JSON; approximate with name match or verified pair
                name_match = bool(skl_stem) and any(
                    stem_of(a).startswith(skl_stem) for a in ani_list)
                keep = (sid_i, st_no) in verified or name_match
                if not keep:
                    continue
                used_states.append(st_no)
                for ani in ani_list:
                    if ani in seen:
                        continue
                    seen.add(ani)
                    motions.append(f"character/{cls}/{ani.lower()}")
            if not motions:
                continue
            effects = []
            for e in rec.get("effect_anis") or []:
                effects.append(f"character/{cls}/{e.lower()}")
            handlers = sorted({st["handler"] for st in states
                               if st.get("handler") and st["state"] in used_states})
            evidence = ("1031 DNF.exe setState: states " +
                        ",".join(map(str, sorted(set(used_states))[:6])) +
                        (f" (+{len(used_states)-6} more)" if len(used_states) > 6 else "") +
                        ("; handlers " + ",".join(handlers[:3]) if handlers else ""))
            rows.append((int(sid), motions, effects, evidence))
        rows.sort()
        jobs.append((cls, rows))
        total_skills += len(rows)

    out = []
    out.append("// Generated by tools/skill-bindings/src/gen_exe_bindings_header.py")
    out.append("// Source: 1031 DNF.exe skill setState tables (disk plaintext) + PVF CHR/etc tables.")
    out.append("// Each binding: skill_id -> ordered body .ani chain (exe vtable+0x49C immediates)")
    out.append("//                + effect .ani chain (sqr/common.nut sq_LoadSkillEffect).")
    out.append("// Keyed by CHR stem (character/<class>/<class>.chr) and PVF skill id.")
    out.append("#pragma once")
    out.append("")
    out.append("#include <cstddef>")
    out.append("")
    out.append("namespace dnf::exe_bindings {")
    out.append("")
    out.append("struct ExeSkillBinding {")
    out.append("    int skillId;")
    out.append("    const char *const *motions; // PVF paths, release order, deduped")
    out.append("    size_t motionCount;")
    out.append("    const char *const *effects;")
    out.append("    size_t effectCount;")
    out.append("    const char *evidence;")
    out.append("};")
    out.append("")
    out.append("struct ExeJobBindings {")
    out.append("    const char *job; // CHR file stem, e.g. \"swordman\", \"atfighter\"")
    out.append("    const ExeSkillBinding *skills;")
    out.append("    size_t count;")
    out.append("};")
    out.append("")

    # emit per-class skill arrays
    job_refs = []
    for cls, rows in jobs:
        if not rows:
            continue
        for sid, motions, effects, evidence in rows:
            arr = f"k_motions_{cls}_{sid}"
            out.append(f"static const char *const {arr}[] = {{")
            for m in motions:
                out.append(f"    {hpp_str(m)},")
            out.append("};")
            if effects:
                arr_e = f"k_effects_{cls}_{sid}"
                out.append(f"static const char *const {arr_e}[] = {{")
                for m in effects:
                    out.append(f"    {hpp_str(m)},")
                out.append("};")
            else:
                arr_e = None
            skill_var = f"k_skill_{cls}_{sid}"
            eff_expr = f"{arr_e}, {len(effects)}, " if arr_e else "nullptr, 0, "
            out.append(f"static const ExeSkillBinding {skill_var} = {{")
            out.append(f"    {sid}, {arr}, {len(motions)}, {eff_expr}")
            out.append(f"    {hpp_str(evidence)}}};")
            job_refs.append((cls, skill_var))
        out.append("")

    # job tables
    job_tables = []
    for cls in CLASSES:
        refs = [(c, s) for c, s in job_refs if c == cls]
        if not refs:
            continue
        tvar = f"k_job_{cls}"
        out.append(f"static const ExeSkillBinding {tvar}_skills[] = {{")
        for _, s in refs:
            out.append(f"    {s},")
        out.append("};")
        out.append(f"static const ExeJobBindings {tvar} = {{")
        out.append(f"    {hpp_str(cls)}, {tvar}_skills, {len(refs)}}};")
        job_tables.append(tvar)
        out.append("")

    out.append("inline const ExeJobBindings *const *jobs(size_t &count) {")
    out.append(f"    static const ExeJobBindings *const k_all[] = {{")
    for t in job_tables:
        out.append(f"        &{t},")
    out.append("    };")
    out.append(f"    count = {len(job_tables)};")
    out.append("    return k_all;")
    out.append("}")
    out.append("")
    out.append("// Lookup by CHR stem and PVF skill id; linear scan is fine at this size.")
    out.append("inline const ExeSkillBinding *find(const char *job, int skillId) {")
    out.append("    size_t n = 0;")
    out.append("    const ExeJobBindings *const *all = jobs(n);")
    out.append("    for (size_t i = 0; i < n; ++i) {")
    out.append("        const ExeJobBindings &j = *all[i];")
    out.append("        bool match = true;")
    out.append("        const char *a = j.job, *b = job;")
    out.append("        for (; *a && *b; ++a, ++b)")
    out.append("            if (*a != *b) { match = false; break; }")
    out.append("        if (match && *a == *b)")
    out.append("            for (size_t k = 0; k < j.count; ++k)")
    out.append("                if (j.skills[k].skillId == skillId) return &j.skills[k];")
    out.append("    }")
    out.append("    return nullptr;")
    out.append("}")
    out.append("")
    out.append("} // namespace dnf::exe_bindings")

    open(OUT, "w", encoding="ascii", newline="\n").write("\n".join(out) + "\n")
    print(f"written {OUT}: {len(job_tables)} jobs, {total_skills} skills")


if __name__ == "__main__":
    main()
